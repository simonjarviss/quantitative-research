"""Step 13: report_tables.md (markdown versions of the main tables, read by RESULTS.md). Cells: mean bp (t) [median]."""
import numpy as np
import pandas as pd
from common import OUT

L = pd.read_csv(OUT / "table_legs.csv")
R = pd.read_csv(OUT / "table_regressions.csv")
X = pd.read_csv(OUT / "table_tax.csv")
P = pd.read_csv(OUT / "table_lp_pnl.csv")
Q = pd.read_csv(OUT / "table_pricing.csv")
D = pd.read_csv(OUT / "table_dax_moves.csv")
A = pd.read_csv(OUT / "table_auction_2025.csv")
B = pd.read_csv(OUT / "table_borrow_2025_26.csv")
PI = pd.read_csv(OUT / "table_pi.csv")
FAM = ["US Russell", "CA S&P/TSX", "EU STOXX 600", "EU DAX family"]
GRP = {"US Russell": ["add", "delete", "R1000->R2000", "R2000->R1000", "add | price >= $5", "add | price < $5",
                      "delete | price >= $5", "delete | price < $5"],
       "CA S&P/TSX": ["add", "delete"], "EU STOXX 600": ["add", "delete"], "EU DAX family": ["net buy", "net sell"]}


def cell(m, t, med=None):
    if pd.isna(m):
        return "–"
    s = f"{m:+.0f}"
    if pd.notna(t):
        s += f" ({t:+.1f})"
    if med is not None and pd.notna(med):
        s += f" [{med:+.0f}]"
    return s


out = ["# Report tables (generated by s13_report.py)\n",
       "Cells: mean in bp (t clustered by event date) [median]. Signed: + = price moved in the direction of index demand.\n"]
legs = [("d0", "T-1→T"), ("d0_id", "T open→T close"), ("on1", "T→T+1 open"), ("id1", "T+1 open→close"), ("r1", "T→T+1 close"),
        ("r2_5", "T+1→T+5"), ("r6_20", "T+5→T+20"), ("r1_20", "T→T+20")]
for basis in ["matched control", "index-adjusted"]:
    out.append(f"\n## Legs by market x side x period ({basis})\n")
    out.append("| family | group | period | n | " + " | ".join(l for _, l in legs) + " |")
    out.append("|" + "---|" * (4 + len(legs)))
    for fam in FAM:
        for g in GRP[fam]:
            for per in ["all", "pre-2016", "2016+"]:
                d = L[(L.basis == basis) & (L.family == fam) & (L.group == g) & (L.period == per)].set_index("leg")
                if d.empty:
                    continue
                n = int(d.loc["d0", "n"])
                cs = [cell(d.loc[k, "mean_bp"], d.loc[k, "t"], d.loc[k, "median_bp"] if basis == "matched control" else None) for k, _ in legs]
                out.append(f"| {fam} | {g} | {per} | {n} | " + " | ".join(cs) + " |")

out.append("\n## Trimmed means (2.5% each tail), matched control\n")
out.append("| family | group | period | T-1→T | T→T+1 open | T→T+1 close | T→T+20 |")
out.append("|---|---|---|---|---|---|---|")
for fam in FAM:
    for g in GRP[fam][:2] if fam != "US Russell" else GRP[fam][:4]:
        for per in ["all", "2016+"]:
            d = L[(L.basis == "matched control") & (L.family == fam) & (L.group == g) & (L.period == per)].set_index("leg")
            out.append(f"| {fam} | {g} | {per} | " + " | ".join(f"{d.loc[k, 'trim_bp']:+.0f}" for k in ["d0", "on1", "r1", "r1_20"]) + " |")

out.append("\n## DAX family by move type (UNSIGNED abnormal: + = price rose vs controls); net visible passive demand in %\n")
out.append("| move | n | net pi % | T-1→T | T→T+1 open | T→T+1 close | T→T+5 | T→T+20 |")
out.append("|---|---|---|---|---|---|---|---|")
for mv, d in D[D.period == "all"].groupby("move"):
    d = d.set_index("leg")
    out.append(f"| {mv} | {int(d.loc['d0', 'n'])} | {d.loc['d0', 'pi_net_pct']:+.2f} | " +
               " | ".join(cell(d.loc[k, "mean_bp"], d.loc[k, "t"]) for k in ["d0", "on1", "r1", "r1_5", "r1_20"]) + " |")

out.append("\n## Regressions (bp per 1 SD; t clustered by event date). All events, pooled periods\n")
specs = ["flow", "flow_fe", "flow_groupfe", "flow_baseADV", "realised"]
out.append("| family | spec | term | T-1→T | T→T+1 open | T+1 open→close | T→T+1 close | T→T+5 | T→T+20 | n |")
out.append("|---|---|---|---|---|---|---|---|---|---|")
x = R[(R["sample"] == "all") & ~R.term.isin(["const", "sell side", "2016+", "log market cap"])]
for fam in FAM + ["EU pooled"]:
    for sp in specs + sorted(set(x[x.family == fam].spec) - set(specs)):
        d = x[(x.family == fam) & (x.spec == sp)]
        for term in d.term.unique():
            dd = d[d.term == term].set_index("leg")
            out.append(f"| {fam} | {sp} ({dd.subset.iloc[0]}) | {term} | " +
                       " | ".join(cell(dd.coef_bp.get(k), dd.t.get(k)) for k in ["d0", "on1", "id1", "r1", "r1_5", "r1_20"]) +
                       f" | {int(dd.n.max())} |")
out.append("\n## Regressions, 2016+ only (flow and crowding terms)\n")
out.append("| family | spec | term | T-1→T | T→T+1 open | T→T+1 close | T→T+5 | T→T+20 | n |")
out.append("|---|---|---|---|---|---|---|---|---|")
x = R[(R["sample"] == "2016+") & ~R.term.isin(["const", "sell side", "2016+", "log market cap"])]
for fam in FAM:
    for sp in x[x.family == fam].spec.unique():
        d = x[(x.family == fam) & (x.spec == sp)]
        for term in d.term.unique():
            dd = d[d.term == term].set_index("leg")
            out.append(f"| {fam} | {sp} ({dd.subset.iloc[0]}) | {term} | " +
                       " | ".join(cell(dd.coef_bp.get(k), dd.t.get(k)) for k in ["d0", "on1", "r1", "r1_5", "r1_20"]) +
                       f" | {int(dd.n.max())} |")

out.append("\n## Europe by tax regime and the UK split (STOXX 600 events, all periods)\n")
out.append("| split | cell | group | n | T-5→T-1 | T-1→T | T→T+1 open | T→T+1 close | T→T+5 | T→T+20 |")
out.append("|---|---|---|---|---|---|---|---|---|---|")
for (sp, c, g), d in X[X.period == "all"].groupby(["split", "cell", "group"], sort=False):
    d = d.set_index("leg")
    out.append(f"| {sp} | {c} | {g} | {int(d.loc['d0', 'n'])} | " +
               " | ".join(cell(d.loc[k, "mean_bp"], d.loc[k, "t"]) for k in ["pre5", "d0", "on1", "r1", "r1_5", "r1_20"]) + " |")
out.append("\n2016+ only:\n")
out.append("| split | cell | group | n | T-1→T | T→T+1 open | T→T+1 close | T→T+20 |")
out.append("|---|---|---|---|---|---|---|---|")
for (sp, c, g), d in X[X.period == "2016+"].groupby(["split", "cell", "group"], sort=False):
    d = d.set_index("leg")
    out.append(f"| {sp} | {c} | {g} | {int(d.loc['d0', 'n'])} | " +
               " | ".join(cell(d.loc[k, "mean_bp"], d.loc[k, "t"]) for k in ["d0", "on1", "r1", "r1_20"]) + " |")

out.append("\n## Liquidity supplier at the T close (matched-control hedge): gross bp per unit, and per event date at 10% of predicted demand\n")
out.append("| family | group | period | exit | n | mean bp (t) [median] | event dates | basket bp (t) | dates > 0 | supplied per date, median (m) | P&L per date, mean (m) (t) | value-weighted bp |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
y = P[(P.basis == "matched control") & P.period.isin(["all", "2016+"])]
for r in y.itertuples():
    out.append(f"| {r.family} | {r.group} | {r.period} | {r.exit} | {r.name_n} | {cell(r.name_mean_bp, r.name_t, r.name_median_bp)} | "
               f"{r.n_event_dates} | {cell(r.basket_mean_bp, r.basket_t)} | {r.basket_share_pos:.0%} | {r.ccy} {r.cap_per_date_median_m:,.1f} | "
               f"{r.pnl_per_date_mean_m:+,.2f} ({r.pnl_per_date_t:+.1f}) | {r.dollar_weighted_bp:+.0f} |")
out.append("\nSame, index-hedged and unhedged (all periods):\n")
out.append("| family | group | exit | index-hedged bp (t) | unhedged bp (t) |")
out.append("|---|---|---|---|---|")
for (f, g, e), d in P[P.period == "all"].groupby(["family", "group", "exit"], sort=False):
    d = d.set_index("basis")
    out.append(f"| {f} | {g} | {e} | {cell(d.loc['index-hedged', 'name_mean_bp'], d.loc['index-hedged', 'name_t'])} | "
               f"{cell(d.loc['unhedged', 'name_mean_bp'], d.loc['unhedged', 'name_t'])} |")

out.append("\n## Pricing buckets (2016+): flow/ADV tercile within family x side\n")
out.append("| family | group | flow tercile | crowding | n | median flow/ADV | E[T-1→T] bp (t) | E[reversal to T+1 close] | E[reversal to T+5] | SD per name T→T+5 | SD basket T→T+5 | quote = E[d0] + 0.25 SD name |")
out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in Q[Q.period == "2016+"].itertuples():
    out.append(f"| {r.family} | {r.group} | {r.flow_tercile} | {r.crowding} | {r.n} | {r.flow_adv_median:.1f} | {cell(r.d0_mean_bp, r.d0_t)} | "
               f"{cell(r.rev_r1_mean_bp, r.rev_r1_t)} | {cell(r.rev_r1_5_mean_bp, r.rev_r1_5_t)} | {r.rev_r1_5_sd_name_bp:.0f} | "
               f"{r.rev_r1_5_sd_basket_bp:.0f} | {r.quote_name_bp_hold5:+.0f} |")

out.append("\n## Russell 27 Jun 2025: closing-auction deviation (official close vs 15:59 SIP bar, minus IWM), signed\n")
out.append("| group | price | n | auction dev bp (t) [median] | T-1→T bp | auction share of T-1→T | T→T+1 open bp | corr(dev, overnight) |")
out.append("|---|---|---|---|---|---|---|---|")
for r in A.itertuples():
    out.append(f"| {r.group} | {r.price} | {r.dev_n} | {cell(r.dev_mean_bp, r.dev_t, r.dev_median_bp)} | {r.d0_mean_bp:+.0f} | "
               f"{r.auction_share_of_d0:+.2f} | {r.on1_mean_bp:+.0f} | {r.corr_dev_on1:+.2f} |")

out.append("\n## Borrow (IBKR indicative via iBorrowDesk), 2025-26 reviews: median fee % p.a.\n")
out.append("| family | group | n | fee T-7d | fee T | fee T+7d | max fee T | T-1→T bp | T→T+1 close bp |")
out.append("|---|---|---|---|---|---|---|---|---|")
for (f, g), d in B.groupby(["family", "group"]):
    out.append(f"| {f} | {g} | {len(d)} | {d.fee_Tm7.median():.2f} | {d.fee_T.median():.2f} | {d.fee_Tp7.median():.2f} | "
               f"{d.fee_T.max():.2f} | {d.s_d0_bp.mean():+.0f} | {d.s_r1_bp.mean():+.0f} |")
out.append("\n## Passive shares used\n")
out.append(PI[["family", "pi_used", "pi_r2_median_2023_26", "pi_r2_last", "source"]].to_markdown(index=False, floatfmt=".4f"))
(OUT / "report_tables.md").write_text("\n".join(out) + "\n")
print("report_tables.md", len(out), "lines")
