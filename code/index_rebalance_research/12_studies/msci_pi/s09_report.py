"""Step 9: markdown tables for RESULTS.md -> report_tables.md, table_pi_summary.csv, table_events_by_review.csv."""
import numpy as np
import pandas as pd

from common import DATA, OUT
from s05_pi_series import pi_at

FAMS = ["MSCI_CANADA", "MSCI_CANADA_SC", "MSCI_EUROPE", "MSCI_EUROPE_SC", "MSCI_EUROPE_GB", "MSCI_EUROPE_FR",
        "MSCI_EUROPE_DE", "MSCI_EUROPE_CH", "MSCI_EUROPE_NL", "MSCI_EUROPE_SE"]


def md(df, fmt=None):
    cols = list(df.columns)
    L = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        L.append("| " + " | ".join(fmt(c, v) if fmt else str(v) for c, v in zip(cols, r)) + " |")
    return "\n".join(L)


def main():
    S = pd.read_parquet(DATA / "pi_series.parquet")
    P = pd.read_csv(OUT / "pi_rows_appended.csv", parse_dates=["date"])
    out = ["# msci_pi report tables (generated by s09_report.py)\n"]
    # A. visible pi, June of each year (last value for 2026)
    dates = [pd.Timestamp(f"{y}-06-30") for y in range(2018, 2026)] + [pd.Timestamp("2025-12-31"), pd.Timestamp("2026-07-01")]
    A = pd.DataFrame({f: [pi_at(S, f, d) * 100 for d in dates] for f in FAMS}, index=[d.date() for d in dates]).T
    A.columns = [str(c) for c in A.columns]
    A.insert(0, "family", A.index)
    A.to_csv(OUT / "table_pi_summary.csv", index=False)
    out += ["## A. Visible pi, % of the segment's float (holders: Standard + IMI funds; Small Cap + IMI funds)\n",
            md(A, lambda c, v: v if c == "family" else f"{v:.2f}"), ""]
    # B. latest pi_true
    last = P.sort_values("date").groupby("family").tail(1)
    last = last[last.family.isin(FAMS)].set_index("family").loc[FAMS].reset_index()
    B = last[["family", "date", "pi_visible", "R", "R_se", "pi_true"]].copy()
    B["pi_visible"] = (B.pi_visible * 100).round(2)
    B["pi_true"] = (B.pi_true * 100).round(1)
    B["R"] = B.R.round(2)
    B["R_se"] = B.R_se.round(2)
    B["date"] = B.date.dt.date
    out += ["## B. Latest rows appended to pi_calibration.csv (pi in %)\n", md(B), ""]
    # C. composition of visible pi at 2025-12-31
    F = pd.read_parquet(DATA / "pi_funds.parquet")
    q = F.q.max()
    for seg, mkt, lab in (("STD", "CA", "MSCI Canada Standard"), ("STD", "EU", "MSCI Europe Standard"),
                          ("SC", "CA", "MSCI Canada Small Cap"), ("SC", "EU", "MSCI Europe Small Cap")):
        x = F[(F.q == q) & (F.seg == seg) & (F.mkt == mkt)].copy()
        W = x.groupby("ctry").W.first()
        x["kw"] = x.k * x.ctry.map(W / W.sum())
        t = x.groupby(["fundname", "ftype"]).kw.sum().sort_values(ascending=False) * 100
        top = t.head(10).reset_index().rename(columns={"kw": "pi_%", "ftype": "type"})
        top["pi_%"] = top["pi_%"].round(3)
        out += [f"## C. {lab}: largest visible holders, {q.date()} (total {t.sum():.2f}%, {x.fundno.nunique()} funds; "
                f"IMI funds {t[t.index.get_level_values(1) == 'IMI'].sum():.2f}%)\n", md(top), ""]
    # D. R
    T = pd.read_csv(OUT / "table_R.csv")
    Tt = pd.read_csv(OUT / "table_R_by_type.csv")
    D = T[["sample", "R", "se", "t", "n", "dates", "n_events"] + (["iqr"] if "iqr" in T else [])].copy()
    for c in ("R", "se", "t"):
        D[c] = D[c].round(2)
    out += ["## D. R fits (table_R.csv)\n", md(D.fillna("")), ""]
    Dt = Tt[["sample", "term", "R", "se", "t", "n", "dates"]].copy()
    for c in ("R", "se", "t"):
        Dt[c] = Dt[c].round(2)
    out += ["## E. R by event type (table_R_by_type.csv)\n", md(Dt.fillna("")), ""]
    # F. events per review
    E = pd.read_csv(OUT / "events.csv")
    ev = ["ADD_STD", "DEL_STD", "MIG_UP", "MIG_DOWN", "ADD_SC", "DEL_SC", "W_STD"]
    G = E[E.event.isin(ev)].groupby(["review", "mkt", "event"]).size().unstack("event").reindex(columns=ev).fillna(0).astype(int)
    G = G.unstack("mkt").swaplevel(axis=1).sort_index(axis=1)
    G.columns = [f"{m} {e}" for m, e in G.columns]
    G = G.reset_index()
    G.to_csv(OUT / "table_events_by_review.csv", index=False)
    tot = E[E.event.isin(ev)].groupby(["mkt", "event"]).size().unstack("event").reindex(columns=ev).fillna(0).astype(int).reset_index()
    out += ["## F. Holdings-implied events, totals 2018-02 .. 2026-08 (per review: table_events_by_review.csv)\n", md(tot), ""]
    C = pd.read_csv(OUT / "table_checks.csv")
    C["value"] = C.value.round(4)
    out += ["## G. Checks (table_checks.csv)\n", md(C.fillna("")), ""]
    (OUT / "report_tables.md").write_text("\n".join(out) + "\n")
    print("\n".join(out[:12]))


if __name__ == "__main__":
    main()
